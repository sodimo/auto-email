/**
 * SMTP seam. `Mailer` is the ONLY interface dispatch.ts knows about, which is
 * what lets the tests exercise the full send path without touching a socket.
 *
 * Transport is worker-mailer (raw TCP via `cloudflare:sockets`). Port 25 is
 * blocked on Workers and is never used here.
 */
import { LogLevel, WorkerMailer } from "worker-mailer";
import type { Env, Settings } from "../types.js";

export interface OutboundMessage {
  to: { email: string; name?: string | null };
  from: { email: string; name: string };
  replyTo?: string;
  subject: string;
  html: string;
  text: string;
  /** RFC 5322 Message-ID, generated by us so it can be logged before sending. */
  messageId: string;
}

export interface MailerResult {
  messageId: string;
  /** Human-readable outcome; see the note on raw replies below. */
  response: string;
}

export interface Mailer {
  send(message: OutboundMessage): Promise<MailerResult>;
}

export interface SmtpConfig {
  host: string;
  port: number;
  username: string;
  password: string;
}

/** `<uuid@sodimo.eu>`, derived from the From address so it passes DMARC alignment. */
export function newMessageId(fromAddress: string): string {
  const domain = fromAddress.split("@").pop() || "sodimo.eu";
  return `<${crypto.randomUUID()}@${domain}>`;
}

export function smtpConfigFromSettings(settings: Settings, env: Env): SmtpConfig {
  const host = settings.smtp_host;
  const username = settings.from_address;
  if (!host) throw new Error("settings.smtp_host is not configured");
  if (!username) throw new Error("settings.from_address is not configured");

  const port = Number(settings.smtp_port);
  if (!Number.isInteger(port) || port <= 0) {
    throw new Error(`settings.smtp_port is not a port number: ${settings.smtp_port}`);
  }
  if (port === 25) {
    throw new Error("port 25 is unavailable on Cloudflare Workers — use 465 (SSL) or 587 (STARTTLS)");
  }
  if (!env.STRATO_SMTP_PASSWORD) {
    throw new Error("STRATO_SMTP_PASSWORD secret is not set on this Worker");
  }
  return { host, port, username, password: env.STRATO_SMTP_PASSWORD };
}

export class StratoMailer implements Mailer {
  constructor(private readonly config: SmtpConfig) {}

  async send(message: OutboundMessage): Promise<MailerResult> {
    // 465 is implicit TLS from the first byte; 587 starts plaintext and is
    // upgraded with STARTTLS. Switching between them is a `settings.smtp_port`
    // change — there is deliberately NO automatic fallback, because a retry
    // after an error we cannot place relative to the DATA command could deliver
    // the same mail twice, and "never goes twice" outranks availability here.
    const implicitTls = this.config.port === 465;

    const connection = await WorkerMailer.connect({
      host: this.config.host,
      port: this.config.port,
      secure: implicitTls,
      startTls: !implicitTls,
      credentials: { username: this.config.username, password: this.config.password },
      authType: "login",
      logLevel: LogLevel.WARN,
      socketTimeoutMs: 20_000,
      responseTimeoutMs: 20_000,
    });

    try {
      await connection.send({
        from: { name: message.from.name, email: message.from.email },
        to: message.to.name ? { name: message.to.name, email: message.to.email } : message.to.email,
        ...(message.replyTo ? { reply: message.replyTo } : {}),
        subject: message.subject,
        text: message.text,
        html: message.html,
        // worker-mailer only generates a Message-ID when the caller has not
        // supplied one, so ours wins and matches what send_log recorded.
        headers: {
          "Message-ID": message.messageId,
          "Auto-Submitted": "auto-generated",
          "X-Auto-Response-Suppress": "All",
        },
      });
    } finally {
      // A failure to close cleanly must not mask a successful delivery.
      await connection.close().catch(() => undefined);
    }

    // worker-mailer's send() resolves void once the server has accepted the
    // message and gives no access to the raw reply line, so this is a
    // reconstruction, not a transcript.
    return {
      messageId: message.messageId,
      response: `accepted by ${this.config.host}:${this.config.port}`,
    };
  }
}

/** One connection per message. Volumes are a handful of mails per run, and
 *  isolating each attempt keeps one bad address from poisoning the rest. */
export function createMailer(settings: Settings, env: Env): Mailer {
  return new StratoMailer(smtpConfigFromSettings(settings, env));
}
